//! Fold a `#[contracttype]` enum's decode-and-re-encode back to the value.
//!
//! timelock's `deposit` takes a `TimeBound` and stores it inside a
//! `ClaimableBalance`. The source passes it straight through; the compiler
//! does not. It decodes the enum field to a discriminant on the way in and
//! builds the variant's `Val` again on the way out, and the choice of
//! which variant to build is a branch the source never wrote:
//!
//! ```text
//! if kind == Before { s = sym "Before" }      →   (gone; the slot holds
//! else              { s = sym "After"  }           `kind` either way)
//! v = encode(s)
//! store slot <- v
//! ```
//!
//! # The rewrite
//!
//! Each arm's encoded value becomes the enum value itself, and the encoder
//! call it came from is elided. Both arms then store the same thing, so
//! the frame meet forwards it to the load that reads the slot, the stores
//! die, and the branch is left choosing between two ways of doing nothing
//! — which [`crate::OverflowGuardElisionPass`] already collects.
//!
//! # Why it is exact
//!
//! Arm by arm. The branch reaches an arm exactly when the value is that
//! arm's variant, and that arm builds the encoding of that variant, so on
//! that path the encoded value *is* the encoding of the value. Substituting
//! one for the other changes nothing on either path.
//!
//! The encoder call goes for the reason every marshalling elision goes:
//! the reconstruction writes the enum into a `#[contracttype]` struct, and
//! the derive builds the same one-element `Vec` from the same variant.
//!
//! # Gates
//!
//! - **Every arm, and every variant.** The union's variants must be
//!   payload-free and exactly covered by the arms, each arm encoding the
//!   one its condition names. An arm encoding a different variant is not
//!   this pattern; an uncovered variant means the branch decides something
//!   else as well.
//! - **One survivor per call.** The encoder returns a `Result` whose
//!   discriminant the call-site constant fold has already settled, so
//!   exactly one projection may be left — the payload. More than one and
//!   the caller is still reading something this pass cannot account for.

use sordec_common::{Provenance, ProvenanceSource, ValueId};
use sordec_ir::{
    BinaryOp, Expr, HighFunction, HighIr, IrType, KnownOp, KnownType, Literal, Region, SemanticOp,
    UnionDef,
};

use crate::dataflow::{block_containing, resolve_use};
use crate::metrics_catalog::MARSHALLING_ENUM_ENCODES as M_ENCODES;
use crate::pass::{Pass, PassResult};

/// Pass name — also the provenance `pass` field for every rewrite.
pub const PASS_NAME: &str = "marshalling-enum-encode";

/// Folds an enum re-encode back to the enum.
#[derive(Debug, Default, Clone, Copy)]
pub struct EnumEncodePass;

/// One arm's encoding, and what it should be replaced by.
struct Fold {
    /// The surviving projection that carried the encoded value.
    payload: ValueId,
    /// The encoder call to elide.
    call: ValueId,
    /// The variant's symbol, which existed only to feed that call.
    symbol: ValueId,
    /// The enum value the encoding is of.
    value: ValueId,
    /// That value's type.
    ty: IrType,
}

impl Pass<HighIr> for EnumEncodePass {
    fn name(&self) -> &'static str {
        PASS_NAME
    }

    fn run(&self, ir: &mut HighIr) -> PassResult {
        let mut result = PassResult::default();
        let Some(facts) = ir.soroban_facts.as_ref() else {
            return result;
        };
        let unions: Vec<UnionDef> = facts.types.unions.clone();
        if unions.is_empty() {
            return result;
        }
        for func in &mut ir.functions {
            let mut folds = Vec::new();
            func.region.for_each_node(|node| collect(func, &unions, node, &mut folds));
            for fold in folds {
                if let Some(b) = func.bindings.get_mut(fold.payload) {
                    b.expr = Expr::Use(fold.value);
                    b.ty = fold.ty;
                    b.add_provenance(Provenance::new(
                        PASS_NAME,
                        ProvenanceSource::SdkPattern,
                        "on this arm the encoded variant is the value itself",
                    ));
                }
                // The call and the symbol it was given: both exist only
                // to build the encoding this fold just replaced, and both
                // come back when the reconstruction writes the enum.
                for (id, note) in [
                    (fold.call, "the derived encode, regenerated by writing the enum"),
                    (fold.symbol, "the variant's symbol, built only for that encode"),
                ] {
                    if let Some(b) = func.bindings.get_mut(id) {
                        b.expr = Expr::Literal(Literal::Unit);
                        b.ty = IrType::Known(KnownType::Unit);
                        b.add_provenance(Provenance::new(
                            PASS_NAME,
                            ProvenanceSource::SdkPattern,
                            note,
                        ));
                    }
                }
                result.metrics.increment(M_ENCODES, 1);
                result.changed = true;
            }
        }
        result
    }
}

/// Both arms of a branch that re-encodes the variant it just tested.
fn collect(func: &HighFunction, unions: &[UnionDef], node: &Region, out: &mut Vec<Fold>) {
    let Region::If { cond, then_region, else_region: Some(other) } = node else {
        return;
    };
    let Some((value, name, op)) = variant_test(func, *cond) else {
        return;
    };
    let ty = match func.bindings.get(value) {
        Some(b) => b.ty.clone(),
        None => return,
    };
    let (IrType::Known(KnownType::UserDefined(id)) | IrType::Inferred(KnownType::UserDefined(id))) = ty
    else {
        return;
    };
    let Some(def) = unions.iter().find(|u| u.id == id) else {
        return;
    };
    // Two payload-free variants, and the condition names one of them.
    if def.cases.len() != 2 || def.cases.iter().any(|c| !c.fields.is_empty()) {
        return;
    }
    let Some(named) = def.cases.iter().position(|c| c.name == name) else {
        return;
    };
    // `==` sends the named variant down the taken arm; `!=` the other.
    let (taken, fallen) = match op {
        BinaryOp::Eq => (named, 1 - named),
        _ => (1 - named, named),
    };
    let arms = [(&**then_region, taken), (&**other, fallen)];
    let mut found = Vec::with_capacity(2);
    for (arm, index) in arms {
        match encodes(func, arm, &def.cases[index].name) {
            Some((payload, call, symbol)) => {
                found.push(Fold { payload, call, symbol, value, ty: ty.clone() });
            }
            None => return,
        }
    }
    out.extend(found);
}

/// The enum value a condition tests, the variant it names, and how.
fn variant_test(func: &HighFunction, cond: ValueId) -> Option<(ValueId, String, BinaryOp)> {
    let Expr::Binary { op: op @ (BinaryOp::Eq | BinaryOp::Ne), lhs, rhs } =
        &func.bindings.get(resolve_use(func, cond))?.expr
    else {
        return None;
    };
    [(*lhs, *rhs), (*rhs, *lhs)].into_iter().find_map(|(value, variant)| {
        let Expr::Variant { name } = &func.bindings.get(resolve_use(func, variant))?.expr else {
            return None;
        };
        Some((resolve_use(func, value), name.clone(), *op))
    })
}

/// The arm's encoding of `variant`: the projection carrying it and the
/// call that produced it.
fn encodes(func: &HighFunction, arm: &Region, variant: &str) -> Option<(ValueId, ValueId, ValueId)> {
    let mut blocks = Vec::new();
    arm.for_each_node(|node| {
        if let Region::Basic(b) = node {
            blocks.push(*b);
        }
    });
    let here = |id: ValueId| block_containing(func, id).is_some_and(|b| blocks.contains(&b));
    // The symbol this arm builds, which must be the variant's own name.
    let symbol = func.bindings.iter().find_map(|(id, b)| {
        matches!(
            &b.expr,
            Expr::Semantic(SemanticOp::Known(KnownOp::SymbolNew { resolved: Some(text), .. }))
                if text == variant
        )
        .then_some(id)
        .filter(|id| here(*id))
    })?;
    // The call that consumes it, in this arm.
    let call = func.bindings.iter().find_map(|(id, b)| {
        let Expr::Call { args, .. } = &b.expr else {
            return None;
        };
        (here(id) && args.iter().any(|a| resolve_use(func, *a) == symbol)).then_some(id)
    })?;
    // Exactly one projection of it survives: the payload.
    let mut projections = func.bindings.iter().filter_map(|(id, b)| {
        matches!(&b.expr, Expr::Project { value, .. } if resolve_use(func, *value) == call)
            .then_some(id)
    });
    let payload = projections.next()?;
    projections.next().is_none().then_some((payload, call, symbol))
}
